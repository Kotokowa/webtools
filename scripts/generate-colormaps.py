"""Generate matching browser/Python color tables using standard palette formulas."""
import colorsys
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
def clamp(x): return max(0., min(1., x))
def byte(x): return int(clamp(x)*255+.5)
tables = {name: [] for name in ('jet', 'hot', 'cool', 'gray', 'hsv', 'blue-white-red')}
stops = ((27,66,122),(56,140,178),(241,246,247),(234,147,91),(165,44,47))
for i in range(256):
    x = i/255
    # MATLAB jet(256): the first sample is at 1/256, rather than zero.
    t = (i+1)/256
    tables['jet'].append([byte(1.5-abs(4*t-k)) for k in (3,2,1)])
    tables['hot'].append([byte((i+1)/96),byte((i+1-96)/96),byte((i+1-192)/64)])
    tables['cool'].append([byte(x),byte(1-x),255])
    tables['gray'].append([i,i,i])
    tables['hsv'].append([byte(v) for v in colorsys.hsv_to_rgb(i/256,1,1)])
    j=min(int(x*4),3);f=x*4-j
    tables['blue-white-red'].append([int(stops[j][c]*(1-f)+stops[j+1][c]*f+.5) for c in range(3)])
data=json.dumps(tables,separators=(',',':'))
(ROOT/'waterwave/colormaps.json').write_text(data+'\n',encoding='utf-8')
(ROOT/'src/water-wave/colormaps.js').write_text("// Generated by scripts/generate-colormaps.py.\nglobalThis.WaterWaveColors="+data+';\n',encoding='utf-8')
